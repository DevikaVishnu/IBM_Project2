import { useState } from "react";
import { Chip, Empty, Excerpt, ORIGIN, OriginTag, ResultChip, card, eyebrow, fmt, linkBtn, mono, v } from "./theme.jsx";

// "How it's built": one claim followed from raw trace records to the screen, in six stages.  Every value
// shown here is read from the bundle (bundle.walkthrough plus the claim, evidence, skeleton and matrix
// entries it points to); the component holds no trace values of its own.

const KIND = {
  observed: { word: "data", desc: "recorded in the raw trace" },
  computed: { word: "generated by code", desc: "deterministic code: adapter, verifier, comparator" },
  "hand-annotated": { word: "drawn by hand", desc: "written by a person; illustrative, not gold" },
};
const PREVIEW_LINES = 8;
const callNo = id => String(id ?? "").replace(/^ev:llm:/, "");

function KindTag({ origin }) {
  const o = ORIGIN[origin];
  return (
    <span style={{ display: "inline-flex", alignItems: "center", gap: 6, fontSize: 12.5, color: o.color }}>
      <OriginTag origin={origin} /><span style={{ fontWeight: 600 }}>{KIND[origin]?.word}</span>
    </span>
  );
}

function Stage({ origin, caption, children, testid }) {
  const o = ORIGIN[origin];
  return (
    <div data-testid={testid} style={{ display: "grid", gridTemplateColumns: "minmax(220px, 300px) minmax(0, 1fr)", gap: 18, alignItems: "start",
      borderLeft: `4px solid ${o.color}`, paddingLeft: 16 }}>
      <div style={{ fontSize: 14, lineHeight: 1.6, color: v("ink") }}>
        <KindTag origin={origin} />
        <div style={{ marginTop: 8 }}>{caption}</div>
      </div>
      <div style={{ minWidth: 0, display: "grid", gap: 10 }}>{children}</div>
    </div>
  );
}

function Box({ title, children, origin }) {
  return (
    <div style={{ border: `1px solid ${v("line")}`, borderRadius: 8, padding: "10px 12px", background: v("surface") }}>
      {(title || origin) && <div style={{ display: "flex", gap: 8, alignItems: "center", marginBottom: 6 }}>{title && <span style={eyebrow}>{title}</span>}{origin && <OriginTag origin={origin} />}</div>}
      {children}
    </div>
  );
}

const td = { padding: "4px 10px 4px 0", verticalAlign: "top", fontSize: 12.5 };

function RecordTable({ records }) {
  return (
    <div style={{ overflowX: "auto" }} tabIndex={0} role="region" aria-label="Raw trace records">
      <table style={{ borderCollapse: "collapse", width: "100%" }}>
        <thead><tr>{["step", "record type", "details"].map(h => <th key={h} style={{ ...td, textAlign: "left", ...eyebrow }}>{h}</th>)}</tr></thead>
        <tbody>
          {records.map(r => {
            const { seq, type, agent_id, tool_call_id, ...rest } = r;
            return (
              <tr key={seq} style={{ borderTop: `1px solid ${v("soft")}` }}>
                <td style={{ ...td, ...mono }}>{seq}</td>
                <td style={{ ...td, ...mono, fontWeight: 600 }}>{type}</td>
                <td style={{ ...td, ...mono, color: v("muted"), overflowWrap: "anywhere", wordBreak: "normal" }}>
                  {Object.entries(rest).map(([k, val]) => `${k.replace(/_prefix$/, "")}=${typeof val === "string" && k.endsWith("_prefix") ? `${val}…` : val}`).join("  ")}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

function Json({ label, origin, value }) {
  return (
    <details style={{ border: `1px solid ${v("line")}`, borderRadius: 8, padding: "6px 10px", background: v("surface") }}>
      <summary style={{ cursor: "pointer", fontSize: 13, display: "flex", gap: 8, alignItems: "center" }}><span style={mono}>{label}</span><OriginTag origin={origin} /></summary>
      <pre tabIndex={0} style={{ ...mono, fontSize: 12, lineHeight: 1.5, whiteSpace: "pre-wrap", wordBreak: "break-word", margin: "8px 0 2px", maxHeight: 260, overflow: "auto", background: v("canvas"), padding: 8, borderRadius: 6 }}>
        {JSON.stringify(value, null, 2)}
      </pre>
    </details>
  );
}

export default function WalkthroughPanel({ b, onOpenClaim, onShowInMatrix }) {
  const [stage, setStage] = useState(0);
  const w = b.walkthrough;
  if (!w) return <Empty testid="walkthrough-empty">This trace's bundle has no build walkthrough. The walkthrough follows one claim of the single-agent AssetOpsBench run, from raw records to the screen.</Empty>;

  const claim = b.claims.find(c => c.id === w.claim);
  const prop = b.propositions.find(p => p.id === claim?.proposition);
  const ev = b.evidence[w.evidence];
  const toolEv = b.skeleton?.events?.find(e => e.id === w.tool_event);
  const counts = b.skeleton?.counts ?? {};
  const delivers = w.adapter.delivers;
  const first = delivers.find(d => d.event === w.first_receiver);
  const atClaim = delivers.find(d => d.event === claim?.event);
  const start = w.raw.records.find(r => r.type === "tool_start") ?? {};
  const link = claim?.links.find(l => l.evidence === w.evidence);
  const col = b.matrix?.columns.find(c => c.id === claim?.event);
  const lines = (ev?.excerpt?.text ?? "").split("\n");
  const preview = { ...ev?.excerpt, text: lines.slice(0, PREVIEW_LINES).join("\n"), spans: [], to_end: lines.length <= PREVIEW_LINES };
  const o3 = claim?.o3 ?? {};
  const bundleItems = [
    ["claims[…] (this claim)", claim?.origin, claim],
    ["propositions[…]", prop?.origin, prop],
    [`evidence["${w.evidence}"]`, ev?.origin, ev && { ...ev, excerpt: { ...ev.excerpt, text: `${ev.excerpt.text.slice(0, 120)}…` } }],
    ["skeleton.events[…] (tool call)", toolEv?.origin, toolEv],
    ["matrix.columns[…] (claiming call)", col?.origin, col],
    ["walkthrough.comparator", w.comparator.origin, w.comparator],
  ];

  const stages = [
    {
      title: "Raw trace", origin: "observed",
      caption: <>The instrumented run records each step. Here the agent calls <span style={mono}>{start.tool}</span> for {fmt(start["args.limit"])} lines of a file, starting at offset {fmt(start["args.offset"])}. The file is read, the tool returns its result, the result is committed, and the next model call starts with it in its input.</>,
      body: (
        <>
          <Box title={`Records at steps ${w.raw.steps[0]}–${w.raw.steps[1]}`}><RecordTable records={w.raw.records} /></Box>
          <Box title={`The result in call ${callNo(w.first_receiver)}'s input, message ${first?.message_index}`}>
            <Excerpt excerpt={preview} maxHeight={200} />
            <p style={{ margin: "6px 0 0", fontSize: 12.5, color: v("muted") }}>First {Math.min(PREVIEW_LINES, lines.length)} of {lines.length} lines · {fmt(ev?.size)} chars · {first?.byte_identical ? "byte-identical to the tool result" : "differs from the tool result"}</p>
          </Box>
        </>
      ),
    },
    {
      title: "Adapter + verifier", origin: "computed",
      caption: <>A deterministic adapter turns the records into a small set of objects: an event for the tool call, an evidence item for its result, and a <i>delivers</i> link for every model call whose input contains that exact text. An independent verifier re-checks the whole run.</>,
      body: (
        <>
          <Box title="Event" origin={toolEv?.origin}><span style={mono}>{toolEv?.id}</span> · {toolEv?.label} · steps {toolEv?.steps.join("–")} · agent {String(toolEv?.agent).replace(/^agent:/, "")}</Box>
          <Box title="Evidence item" origin={ev?.origin}><span style={mono}>{ev?.id}</span> · {ev?.tool} result · {fmt(ev?.size)} chars · sha256 <span style={mono}>{ev?.sha256?.slice(0, 12)}…</span></Box>
          <Box title={`Delivers links (${delivers.length})`} origin={w.adapter.origin}>
            <div style={{ display: "flex", flexWrap: "wrap", gap: 6 }}>
              {delivers.map(d => (
                <Chip key={d.event} tone={d.event === w.first_receiver || d.event === claim?.event ? "primary" : "muted"} title={d.locator}>
                  call {callNo(d.event)}{d.event === w.first_receiver ? " · first" : ""}{d.event === claim?.event ? " · claiming call" : ""}
                </Chip>
              ))}
            </div>
            <p style={{ margin: "6px 0 0", fontSize: 12.5, color: v("muted") }}>Each link points at message {first?.message_index} of that call's input; all are byte-identical (sha256 equal).</p>
          </Box>
          <Box title="Verifier" origin="computed">
            <b>{fmt(w.adapter.verifier_errors)} errors</b> over the whole run: {fmt(counts.events)} events, {fmt(counts.evidence)} evidence items, {fmt(counts.delivers)} delivers links.
          </Box>
        </>
      ),
    },
    {
      title: "Hand annotation", origin: "hand-annotated",
      caption: <>A person marks what the agent asserted: the exact words in the final answer, the proposition they express, and the state (TRUE). They also link the proposition to the evidence that supports it. This layer is <b>hand-annotated, illustrative</b>, not gold.</>,
      body: (
        <>
          <Box title={`Claim span in the final answer (step ${claim?.step})`} origin={claim?.origin}>
            <blockquote style={{ margin: 0, padding: "6px 10px", borderLeft: "3px solid #F59E0B", background: "#FFFBEB", ...mono, fontSize: 13 }}>{claim?.words}</blockquote>
            <p style={{ margin: "6px 0 0", fontSize: 12.5, color: v("muted") }}>characters {claim?.span?.join("–")} of the answer</p>
          </Box>
          <Box title="Proposition" origin={prop?.origin}><span style={{ fontSize: 13 }}>{prop?.form}</span></Box>
          <Box title="State" origin={claim?.state?.origin}><Chip tone="primary">{claim?.state?.value}</Chip> held by <b>{String(claim?.speaker).replace(/^agent:/, "")}</b> at call {callNo(claim?.event)}</Box>
          <Box title="Link" origin={link?.origin}><Chip tone="primary">{link?.relation}</Chip> → <span style={mono}>{link?.evidence}</span> (the evidence item from stage 2)</Box>
        </>
      ),
    },
    {
      title: "Comparator", origin: "computed",
      caption: <>Code compares the two layers. <b>O2</b> asks whether the evidence was in the claiming call's input. <b>O3</b> compares the stated value with what the linked evidence says, overall and counting only evidence that was in the agent's input.</>,
      body: (
        <>
          <Box title="O2 · exposure_at" origin={w.comparator.origin}>
            {w.comparator.o2.map(o => <div key={o.event} style={{ fontSize: 13.5, marginBottom: 4 }}>call {callNo(o.event)}{o.event === claim?.event ? " (claiming call)" : ""}: <Chip tone={o.value === "DELIVERED" ? "success" : "muted"}>{o.value}</Chip></div>)}
          </Box>
          <Box title="O3 · state_vs_evidence" origin={o3.origin}>
            <div style={{ display: "flex", flexWrap: "wrap", gap: 8, alignItems: "center", fontSize: 13.5 }}>
              <ResultChip value={o3.comparison} /><span style={{ ...mono, fontSize: 12.5 }}>{o3.comparison}</span>
              <span style={{ color: v("muted") }}>direct {o3.direct} · delivered_direct {o3.delivered_direct}</span>
            </div>
            <p style={{ margin: "6px 0 0", fontSize: 13 }}>{o3.meaning}</p>
            <p style={{ margin: "4px 0 0", fontSize: 12.5, color: v("muted") }}>{o3.operation}; computed from {o3.computed_from}{o3.fixture_expected ? `; matches the fixture's expected result (${o3.fixture_expected})` : ""}. Code: <span style={mono}>_semantic_compare.py</span></p>
          </Box>
        </>
      ),
    },
    {
      title: "Trace bundle", origin: "computed",
      caption: <>The builder writes everything into one JSON file per trace. Every item keeps its origin tag, so the screen can always say whether something is data, generated by code, or drawn by hand.</>,
      body: <div style={{ display: "grid", gap: 6 }}>{bundleItems.filter(([, , val]) => val).map(([label, origin, val]) => <Json key={label} label={label} origin={origin ?? "computed"} value={val} />)}</div>,
    },
    {
      title: "On screen", origin: "computed",
      caption: <>The Explorer renders the bundle. The same claim appears as a chain in Claims &amp; evidence and as a marker on its model call in the interaction matrix.</>,
      body: (
        <Box>
          <div style={{ display: "flex", flexWrap: "wrap", gap: 10 }}>
            <button className="be-hover" data-testid="walk-open-claim" onClick={() => onOpenClaim(w.claim)} style={bigBtn}>Open this claim's chain →</button>
            <button className="be-hover" data-testid="walk-open-matrix" onClick={() => onShowInMatrix(claim)} style={bigBtn}>Show its marker in the matrix (column {callNo(claim?.event)}) →</button>
          </div>
        </Box>
      ),
    },
  ];
  const s = stages[stage];
  return (
    <div data-testid="walkthrough" style={{ display: "grid", gap: 14 }}>
      <section style={{ ...card, padding: "16px 18px" }}>
        <div style={{ display: "flex", flexWrap: "wrap", alignItems: "baseline", gap: 10 }}>
          <h2 style={{ margin: 0, fontSize: 17, fontWeight: 700 }}>How it's built</h2>
          <span style={{ fontSize: 13.5, color: v("muted") }}>one claim, from raw trace records to the screen: <b style={{ color: v("ink") }}>{claim?.label}</b></span>
        </div>
        <div role="list" aria-label="Colour key" style={{ display: "flex", flexWrap: "wrap", gap: 16, marginTop: 10 }}>
          {Object.keys(KIND).map(k => <span role="listitem" key={k} title={KIND[k].desc}><KindTag origin={k} /></span>)}
        </div>
        <ol role="tablist" aria-label="Stages" style={{ listStyle: "none", margin: "14px 0 0", padding: 0, display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(140px, 1fr))", gap: 6 }}>
          {stages.map((x, i) => {
            const on = i === stage, o = ORIGIN[x.origin];
            return (
              <li key={x.title}>
                <button role="tab" aria-selected={on} data-testid={`walk-stage-${i + 1}`} onClick={() => setStage(i)} className="be-hover"
                  style={{ width: "100%", textAlign: "left", cursor: "pointer", borderRadius: 8, padding: "8px 10px", borderStyle: "solid",
                    borderWidth: "4px 1.5px 1.5px 1.5px", borderColor: `${o.color} ${on ? o.color : "#E2E8F0"} ${on ? o.color : "#E2E8F0"} ${on ? o.color : "#E2E8F0"}`,
                    background: on ? o.bg : v("surface"), color: v("ink") }}>
                  <span style={{ fontSize: 12, color: o.color, fontWeight: 700 }}>{i + 1} · {KIND[x.origin].word}</span>
                  <span style={{ display: "block", fontSize: 14, fontWeight: on ? 700 : 550 }}>{x.title}</span>
                </button>
              </li>
            );
          })}
        </ol>
      </section>
      <section role="tabpanel" aria-label={s.title} style={{ ...card, padding: "18px 20px" }}>
        <h3 style={{ margin: "0 0 14px", fontSize: 16 }}>{stage + 1}. {s.title}</h3>
        <Stage origin={s.origin} caption={s.caption} testid={`walk-panel-${stage + 1}`}>{s.body}</Stage>
        <div style={{ display: "flex", justifyContent: "space-between", marginTop: 18 }}>
          <button className="be-hover" style={navBtn} disabled={stage === 0} onClick={() => setStage(stage - 1)}>‹ {stage > 0 ? stages[stage - 1].title : "Previous"}</button>
          <button className="be-hover" style={navBtn} disabled={stage === stages.length - 1} onClick={() => setStage(stage + 1)}>{stage < stages.length - 1 ? stages[stage + 1].title : "Next"} ›</button>
        </div>
      </section>
      <p data-testid="walkthrough-note" style={{ margin: 0, fontSize: 13.5, color: v("muted") }}>{w.note}</p>
      <p style={{ margin: 0 }}><button style={linkBtn} onClick={() => onOpenClaim(w.claim)}>Go to Claims &amp; evidence</button></p>
    </div>
  );
}

const bigBtn = { fontSize: 14, padding: "8px 14px", borderRadius: 8, border: "1px solid #2563EB", background: "#EFF6FF", color: "#1D4ED8", cursor: "pointer", fontWeight: 600 };
const navBtn = { fontSize: 13.5, padding: "6px 12px", borderRadius: 7, border: "1px solid #CBD5E1", background: "#FFFFFF", cursor: "pointer", color: "#0F172A" };
